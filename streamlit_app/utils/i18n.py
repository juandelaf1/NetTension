def t(key: str, lang: str = "es") -> str:
    keys = key.split(".")
    d = T.get(lang, T["es"])
    for k in keys:
        if isinstance(d, dict):
            d = d.get(k)
        else:
            return key
    return str(d) if d is not None else key

def lang() -> str:
    import streamlit as st
    lang_map = {"Español": "es", "English": "en"}
    radio_val = st.session_state.get("lang_radio")
    if radio_val in lang_map:
        return lang_map[radio_val]
    return st.session_state.get("lang", "es")
